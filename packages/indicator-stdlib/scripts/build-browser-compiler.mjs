// Bundles the browser compiler.
//
// `asc` and `binaryen` import Node builtins in runtime-guarded branches. Those branches never run in
// a browser, but a bundler resolves them statically, so they are aliased to a throwing stub. Doing
// it at *our* build time means the shipped artifact contains no bare Node specifiers at all — a
// consumer's bundler has nothing to choke on.
//
// Output: dist/compiler/browser.js (~15 MB). Loaded lazily by consumers; see compiler/browser.ts.

import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const stub = resolve(packageRoot, "compiler/stubs/node-builtin.ts");

const NODE_BUILTINS = ["fs", "module", "path", "url", "node:module"];

await build({
  bundle: true,
  entryPoints: [resolve(packageRoot, "compiler/browser.ts")],
  external: ["@assemblyscript/loader"],
  format: "esm",
  logLevel: "info",
  minify: true,
  outfile: resolve(packageRoot, "dist/compiler/browser.js"),
  platform: "browser",
  plugins: [
    {
      name: "stub-node-builtins",
      setup(build) {
        const filter = new RegExp(`^(${NODE_BUILTINS.join("|")})$`);

        build.onResolve({ filter }, (args) => ({ path: stub }));
      },
    },
  ],
  sourcemap: false,
  target: "es2022",
});

// tsup does not emit declarations for this entry (it must not process it — bundling `asc` for Node
// would be wrong), so the types are written here. They re-export from the tsup-built `./index` so
// the two entries cannot drift.
await writeFile(
  resolve(packageRoot, "dist/compiler/browser.d.ts"),
  [
    "// GENERATED by scripts/build-browser-compiler.mjs — do not edit.",
    'export type { CompileScriptOptions, CompileScriptResult } from "./index";',
    'export declare function compileScriptInBrowser(',
    "  source: string,",
    '  options: import("./index").CompileScriptOptions,',
    '): Promise<import("./index").CompileScriptResult>;',
    "",
  ].join("\n"),
);
